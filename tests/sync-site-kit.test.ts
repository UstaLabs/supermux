import { expect, test } from "bun:test"
import { createHash } from "node:crypto"
import { readFileSync } from "node:fs"
import { resolve } from "node:path"
import { KIT_FILES, PIN_PATH, FRAGMENT_PATH, buildFragment } from "../scripts/sync-site-kit"

// What's new (#90): the website's real-app kit (UstaLabs/supermux-website app/) is the source of the editions' scenes.
// The app bundles one copy of it, pinned to a website commit, as a single fragment the edition pages inline.

const fake = (path: string): Uint8Array => new TextEncoder().encode(
  path.endsWith(".woff2") ? `FONT(${path})` : path.endsWith(".css") ? `/* ${path} */ .a{}</style>` : `// ${path}\nvar s = "</script>";`,
)

test("the fragment carries every kit file, scripts in load order, fonts inlined, and the pin it came from", () => {
  const out = buildFragment("abc123", fake)
  expect(out.startsWith("<!-- generated by scripts/sync-site-kit.ts from UstaLabs/supermux-website@abc123")).toBe(true)
  for (const f of KIT_FILES.filter(f => !f.endsWith(".woff2"))) expect(out).toContain(f)
  // replay-data before app.js (app.js reads it as it loads), the runner before its scenes
  const at = (f: string) => out.indexOf(`// ${f}`)
  expect(at("app/replay-data.js")).toBeLessThan(at("app/app.js"))
  expect(at("app/app.js")).toBeLessThan(at("app/scene-kit.js"))
  expect(at("app/scene-kit.js")).toBeLessThan(at("app/browser-scene.js"))
  expect(out).toContain("url(data:font/woff2;base64,")
})

test("nothing in a kit file can end the tag it is inlined in", () => {
  const out = buildFragment("abc123", fake)
  const scripts = out.split("<script>").slice(1).map(s => s.slice(0, s.indexOf("</script>")))
  for (const s of scripts) expect(s).not.toContain("</script")
  expect(out).toContain("<\\/script>")
  expect(out).not.toContain(".a{}</style></style>")
})

test("the bundled kit is exactly what its pin says: nobody edited it by hand", () => {
  const root = resolve(import.meta.dir, "..")
  const pin = JSON.parse(readFileSync(resolve(root, PIN_PATH), "utf8"))
  expect(pin.repo).toBe("UstaLabs/supermux-website")
  expect(pin.sha).toMatch(/^[0-9a-f]{40}$/)
  const fragment = readFileSync(resolve(root, FRAGMENT_PATH))
  expect(createHash("sha256").update(fragment).digest("hex")).toBe(pin.sha256)
  expect(fragment.toString("utf8")).toContain(pin.sha)
})
