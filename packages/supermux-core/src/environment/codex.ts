function ensureHome(home: string): void {
  mkdirSync(home, { recursive: true, mode: 0o700 })
}

function renderCodexConfig(spec: CodexEnvironmentSpec): string {
  const servers = spec.mcpServers.map(renderCodexMcp).join("\n")
  return `# Generated by supermux. Do not edit by hand.
${servers}
# Disable codex's native memory feature — ~/.mux is the sole memory.
[features]
memories = ${spec.nativeMemory}
`
}

function renderCodexMcp(server: McpServerSpec): string {
  const envLines = Object.entries(server.env)
    .map(([key, value]) => `env.${key} = ${JSON.stringify(value)}`)
    .join("\n")
  return `
[mcp_servers.${server.name}]
command = ${JSON.stringify(server.command)}
args = ${JSON.stringify(server.args)}
${envLines}
`
}

/** A Starlark string literal: the escapes of a JSON string (`\"`, `\\`, `\n`, `\uXXXX`) are Starlark's too. */
const literal = (text: string): string => JSON.stringify(text)

/** The programs a shell may use on a readable file, each as the ABSOLUTE path to type (see codexReadRules). */
export type ReadPrograms = { cat?: string; head?: string; tail?: string; wc?: string }

const READERS = ["cat", "head", "tail"] as const
const PROGRAM_NAMES = [...READERS, "wc"] as const
const PLAIN_PROGRAM_PATH = /^\/[A-Za-z0-9._+/-]+$/

function validatePrograms(programs: ReadPrograms): void {
  for (const name of PROGRAM_NAMES) {
    const program = programs[name]
    if (program === undefined) continue
    if (typeof program !== "string" || !PLAIN_PROGRAM_PATH.test(program) || posix.resolve(program) !== program || posix.basename(program) !== name) {
      throw new TypeError(`read program ${name} must be an absolute, canonical path ending in /${name} (letters, digits and . _ + - only), got ${JSON.stringify(program)}`)
    }
  }
}

/**
 * Exec-policy rules (Starlark) that allow a shell to read `files`: `cat`, `head` and `tail` with exactly the
 * file, and `wc -l` with it, each as the ABSOLUTE program in `programs`. A command an allow rule matches in
 * full runs OUTSIDE Codex's sandbox, so the rules must not be reachable by anything but the real binary:
 * - They are keyed by absolute path, never by a bare name. Codex matches a command started by an absolute
 *   path against the rules of its file name too (host-executable resolution is on at run time), so a rule for
 *   `cat` would also allow a planted `./tools/cat`, and a bare `cat` is whatever PATH finds.
 * - `host_executable(name, paths)` narrows that file-name fallback, for any rule of these names (the user's
 *   own among them), to the one trusted path.
 * Every rule carries `match` / `not_match` examples, which Codex checks when it loads the file: that a bare
 *   name, a planted path and a relative path do NOT match is part of the file.
 */
export function codexReadRules(files: readonly string[], programs: ReadPrograms): string {
  validatePrograms(programs)
  const readers = READERS.flatMap(name => (programs[name] ? [programs[name]!] : []))
  const lines = ["# Generated by supermux. Do not edit by hand."]
  for (const name of PROGRAM_NAMES) {
    if (programs[name]) lines.push(`host_executable(name = ${literal(name)}, paths = [${literal(programs[name]!)}])`)
  }
  const justification = literal("supermux: this session's shell may read this file")
  /** The command forms that must NOT match a rule for `program`: its bare name, a planted copy, a relative one. */
  const impostors = (program: string, rest: string[]) => {
    const name = posix.basename(program)
    return [[name], [`${posix.dirname(program)}-evil/${name}`], [`./${name}`]].map(head => [...head, ...rest])
  }
  const render = (rows: string[][]) => `[${rows.map(row => `[${row.map(literal).join(", ")}]`).join(", ")}]`
  for (const file of [...new Set(files)]) {
    const other = `${file}-other`
    if (readers.length > 0) {
      lines.push(
        "prefix_rule(",
        `    pattern = [[${readers.map(literal).join(", ")}], ${literal(file)}],`,
        '    decision = "allow",',
        `    justification = ${justification},`,
        `    match = ${render(readers.map(program => [program, file]))},`,
        `    not_match = ${render([
          ...impostors(readers[0]!, [file]),
          ...(readers.length > 1 ? impostors(readers[readers.length - 1]!, [file]) : []),
          [readers[0]!, other], [readers[readers.length - 1]!, "-n", "1", file], [`${posix.dirname(readers[0]!)}/rm`, file],
        ])},`,
        ")",
      )
    }
    if (programs.wc) {
      lines.push(
        "prefix_rule(",
        `    pattern = [${literal(programs.wc)}, "-l", ${literal(file)}],`,
        '    decision = "allow",',
        `    justification = ${justification},`,
        `    match = ${render([[programs.wc, "-l", file]])},`,
        `    not_match = ${render([...impostors(programs.wc, ["-l", file]), [programs.wc, "-c", file], [programs.wc, file], [programs.wc, "-l", other]])},`,
        ")",
      )
    }
  }
  return [...lines, ""].join("\n")
}

const RULES_NAME = /^supermux-[A-Za-z0-9._-]+$/

function validateReadableFiles(value: unknown): void {
  if (value === undefined) return
  const spec = value as { name?: unknown; files?: unknown; hostBinaries?: unknown } | null
  if (!spec || typeof spec !== "object" || typeof spec.name !== "string" || !RULES_NAME.test(spec.name)) {
    throw new TypeError("readableFiles.name must match /^supermux-[A-Za-z0-9._-]+$/")
  }
  // A lone surrogate is written as `\ud800`, which Codex's parser rejects: it would drop every rule of the home.
  if (!Array.isArray(spec.files) || spec.files.some(f => typeof f !== "string" || f === "/" || !posix.isAbsolute(f) || posix.resolve(f) !== f || /\p{Surrogate}/u.test(f))) {
    throw new TypeError("readableFiles.files must be absolute, canonical, well-formed file paths (no trailing slash, no `..`, `.` or `//` inside)")
  }
  if (spec.hostBinaries !== undefined) {
    const binaries = spec.hostBinaries as { dirs?: unknown; trustedUid?: unknown } | null
    if (!binaries || typeof binaries !== "object" || (binaries.dirs !== undefined && (!Array.isArray(binaries.dirs) || binaries.dirs.some(d => typeof d !== "string")))
      || (binaries.trustedUid !== undefined && (!Number.isInteger(binaries.trustedUid) || (binaries.trustedUid as number) < 0))) {
      throw new TypeError("readableFiles.hostBinaries must be { dirs?: string[], trustedUid?: number }")
    }
  }
}

/** What `prepareCodexEnvironment` reports about `readableFiles`: the programs its rules name, and the ones it could not trust. */
export type CodexReadReport = { readPrograms?: ReadPrograms; unresolvedPrograms?: string[] }

export async function prepareCodexEnvironment(spec: CodexEnvironmentSpec): Promise<PreparedEnvironment & CodexReadReport> {
  requireSpec(spec, [
    ...ENVIRONMENT_FIELDS,
    "credentials",
    "credentials.apiKey",
    "credentials.canonicalHome",
    "nativeMemory",
  ])
  validateMcpServerNames(spec.mcpServers)
  validateReadableFiles(spec.readableFiles)
  ensureHome(spec.home)
  const files: string[] = []

  let credentials: PreparedEnvironment["credentials"]
  const env: Record<string, string> = { CODEX_HOME: spec.home }

  if (spec.credentials.account === true) {
    credentials = "account"
    releaseSessionCredential({
      sessionCopy: join(spec.home, "auth.json"),
      canonical: join(spec.credentials.canonicalHome, "auth.json"),
      freshness: codexCredentialFreshness,
    })
  } else if (spec.credentials.apiKey) {
    credentials = "api_key"
    env.OPENAI_API_KEY = spec.credentials.apiKey
  } else {
    const userAuth = join(spec.credentials.canonicalHome, "auth.json")
    const sessionAuth = join(spec.home, "auth.json")
    // Heal first, copy second. A token this session refreshed goes back to the
    // user's file BEFORE the copy below overwrites it, so a sibling session gets
    // the refreshed token instead of the token it replaced.
    promoteIfNewer({
      sessionCopy: sessionAuth,
      canonical: userAuth,
      freshness: codexCredentialFreshness,
    })
    if (existsSync(userAuth)) {
      copyFileReplace(userAuth, sessionAuth)
      files.push(sessionAuth)
      credentials = "copy"
    } else {
      throw new Error(
        `Codex auth not found at ${userAuth} and OPENAI_API_KEY is unset. ` +
        `Run \`codex login\` first.`,
      )
    }
  }

  const configPath = join(spec.home, "config.toml")
  writeFileSync(configPath, renderCodexConfig(spec), { encoding: "utf8", mode: 0o600 })
  chmodSync(configPath, 0o600)
  files.push(configPath)

  const report: CodexReadReport = {}
  if (spec.readableFiles) {
    // The host's real binaries only (see trustedHostBinary): a program that cannot be trusted gets no rule.
    const programs: ReadPrograms = {}
    const unresolved: string[] = []
    for (const name of PROGRAM_NAMES) {
      const path = trustedHostBinary(name, spec.readableFiles.hostBinaries)
      if (path) programs[name] = path
      else unresolved.push(name)
    }
    const rulesPath = join(spec.home, "rules", `${spec.readableFiles.name}.rules`)
    if (spec.readableFiles.files.length === 0 || Object.keys(programs).length === 0) {
      rmSync(rulesPath, { force: true })
    } else {
      mkdirSync(join(spec.home, "rules"), { recursive: true, mode: 0o700 })
      writeFileNoFollow(rulesPath, codexReadRules(spec.readableFiles.files, programs), 0o600)
      files.push(rulesPath)
    }
    report.readPrograms = spec.readableFiles.files.length === 0 ? {} : programs
    report.unresolvedPrograms = unresolved
  }

  return { env, files, credentials, ...report }
}
