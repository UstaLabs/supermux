import { describe, test, expect, beforeEach, afterEach } from "bun:test"
import { mkdtempSync, rmSync, readFileSync, readdirSync, writeFileSync, existsSync, statSync, mkdirSync, symlinkSync, lstatSync } from "fs"
import { join } from "path"
import { tmpdir } from "os"
import { execFileSync } from "child_process"
import { prepareCodexEnvironment } from "../src/environment/index.js"
import { codexReadRules } from "../src/environment/codex.js"
import type { CodexEnvironmentSpec, McpServerSpec } from "../src/environment/index.js"

function jwt(exp: number): string {
  return ["e30", Buffer.from(JSON.stringify({ exp })).toString("base64url"), "sig"].join(".")
}

function authJson(exp: number): string {
  return JSON.stringify({ tokens: { access_token: jwt(exp) } })
}

const MUX_SHIM: McpServerSpec = {
  name: "mux-shim",
  command: "bun",
  args: ["run", "/path/to/shim/index.ts"],
  env: {
    MUX_SESSION_ID: "zoom",
    MUX_DISPLAY_NAME: "zoom",
    MUX_AGENT_KIND: "codex",
    MUX_SOCKETS_DIR: "/sockets",
  },
}

/** Captured from the broker writeCodexConfig for the same inputs before the move. */
const CODEX_TOML = `# Generated by supermux. Do not edit by hand.

[mcp_servers.mux-shim]
command = "bun"
args = ["run","/path/to/shim/index.ts"]
env.MUX_SESSION_ID = "zoom"
env.MUX_DISPLAY_NAME = "zoom"
env.MUX_AGENT_KIND = "codex"
env.MUX_SOCKETS_DIR = "/sockets"

# Disable codex's native memory feature — ~/.mux is the sole memory.
[features]
memories = false
`

describe("prepareCodexEnvironment", () => {
  let dir: string
  beforeEach(() => { dir = mkdtempSync(join(tmpdir(), "codex-env-")) })
  afterEach(() => { rmSync(dir, { recursive: true, force: true }) })

  function spec(over: Partial<CodexEnvironmentSpec> = {}): CodexEnvironmentSpec {
    return {
      home: join(dir, "session"),
      workdir: join(dir, "wd"),
      mcpServers: [MUX_SHIM],
      skillsPaths: [],
      credentials: { apiKey: "sk-test", canonicalHome: join(dir, "canonical") },
      nativeMemory: false,
      ...over,
    }
  }

  test("config.toml matches the former broker writer byte-for-byte", async () => {
    const prepared = await prepareCodexEnvironment(spec())
    const path = join(dir, "session", "config.toml")
    expect(prepared.files).toContain(path)
    expect(readFileSync(path, "utf8")).toBe(CODEX_TOML)
  })

  test("apiKey wins and does not copy auth.json", async () => {
    mkdirSync(join(dir, "canonical"), { recursive: true })
    writeFileSync(join(dir, "canonical", "auth.json"), authJson(2000))
    const prepared = await prepareCodexEnvironment(spec({ credentials: { apiKey: "sk-test", canonicalHome: join(dir, "canonical") } }))
    expect(prepared.credentials).toBe("api_key")
    expect(prepared.env.OPENAI_API_KEY).toBe("sk-test")
    expect(prepared.env.CODEX_HOME).toBe(join(dir, "session"))
    expect(existsSync(join(dir, "session", "auth.json"))).toBe(false)
  })

  test("copies canonical auth.json after promoteIfNewer", async () => {
    const canonicalHome = join(dir, "canonical")
    mkdirSync(canonicalHome, { recursive: true })
    writeFileSync(join(canonicalHome, "auth.json"), authJson(2000))
    const prepared = await prepareCodexEnvironment(spec({
      credentials: { apiKey: null, canonicalHome },
    }))
    expect(prepared.credentials).toBe("copy")
    expect(prepared.env.OPENAI_API_KEY).toBeUndefined()
    expect(readFileSync(join(dir, "session", "auth.json"), "utf8")).toBe(authJson(2000))
    expect(statSync(join(dir, "session", "auth.json")).mode & 0o777).toBe(0o600)
    expect(prepared.files).toContain(join(dir, "session", "auth.json"))
  })

  test("throws when neither apiKey nor canonical auth exists", async () => {
    const canonicalHome = join(dir, "canonical")
    mkdirSync(canonicalHome, { recursive: true })
    await expect(prepareCodexEnvironment(spec({
      credentials: { apiKey: null, canonicalHome },
    }))).rejects.toThrow(/Codex auth not found/)
  })

  test("heals a newer session copy into the canonical file before copying", async () => {
    const canonicalHome = join(dir, "canonical")
    const sessionHome = join(dir, "session")
    mkdirSync(canonicalHome, { recursive: true })
    mkdirSync(sessionHome, { recursive: true })
    writeFileSync(join(canonicalHome, "auth.json"), authJson(1000))
    writeFileSync(join(sessionHome, "auth.json"), authJson(3000))
    await prepareCodexEnvironment(spec({
      home: sessionHome,
      credentials: { apiKey: null, canonicalHome },
    }))
    expect(readFileSync(join(canonicalHome, "auth.json"), "utf8")).toBe(authJson(3000))
    expect(readFileSync(join(sessionHome, "auth.json"), "utf8")).toBe(authJson(3000))
  })

  test("dest symlink to canonical auth is unlinked; canonical unchanged; session copy is a regular file", async () => {
    const canonicalHome = join(dir, "canonical")
    mkdirSync(canonicalHome, { recursive: true })
    mkdirSync(join(dir, "session"), { recursive: true })
    const canonical = join(canonicalHome, "auth.json")
    writeFileSync(canonical, authJson(2000))
    symlinkSync(canonical, join(dir, "session", "auth.json"))
    await prepareCodexEnvironment(spec({ credentials: { apiKey: null, canonicalHome } }))
    expect(readFileSync(canonical, "utf8")).toBe(authJson(2000))
    expect(lstatSync(join(dir, "session", "auth.json")).isSymbolicLink()).toBe(false)
    expect(statSync(join(dir, "session", "auth.json")).isFile()).toBe(true)
  })

  test("injected MCP name throws TypeError and writes nothing", async () => {
    await expect(prepareCodexEnvironment(spec({
      mcpServers: [{ name: 'x]\\ncommand = "pwned"', command: "true", args: [], env: {} }],
    }))).rejects.toThrow(/mcpServers\[0\]\.name/)
    expect(existsSync(join(dir, "session", "config.toml"))).toBe(false)
  })

  test("requireSpec TypeError names each missing field", async () => {
    const full: any = spec()
    for (const field of ["home", "workdir", "mcpServers", "skillsPaths", "nativeMemory", "credentials"]) {
      const s = { ...full }; delete s[field]
      await expect(prepareCodexEnvironment(s)).rejects.toThrow(new RegExp(`${field} is required`))
    }
    await expect(prepareCodexEnvironment({ ...full, credentials: { canonicalHome: join(dir, "c") } } as any)).rejects.toThrow(/credentials.apiKey is required/)
  })

  test("files lists exactly what was written for apiKey", async () => {
    const prepared = await prepareCodexEnvironment(spec())
    expect(prepared.files).toEqual([join(dir, "session", "config.toml")])
  })
})

const INBOX_FILE = "/home/u/.mux/session_inboxes/abc-123.jsonl"

/** The rules text for INBOX_FILE, spelled out: what Codex is given, character for character. */
const INBOX_RULES = `# Generated by supermux. Do not edit by hand.
prefix_rule(
    pattern = [["cat", "head", "tail"], "/home/u/.mux/session_inboxes/abc-123.jsonl"],
    decision = "allow",
    justification = "supermux: this session's shell may read this file",
    match = [["cat", "/home/u/.mux/session_inboxes/abc-123.jsonl"], ["head", "/home/u/.mux/session_inboxes/abc-123.jsonl"], ["tail", "/home/u/.mux/session_inboxes/abc-123.jsonl"]],
    not_match = [["cat", "/home/u/.mux/session_inboxes/abc-123.jsonl-other"], ["tail", "-n", "1", "/home/u/.mux/session_inboxes/abc-123.jsonl"], ["rm", "/home/u/.mux/session_inboxes/abc-123.jsonl"]],
)
prefix_rule(
    pattern = ["wc", "-l", "/home/u/.mux/session_inboxes/abc-123.jsonl"],
    decision = "allow",
    justification = "supermux: this session's shell may read this file",
    match = [["wc", "-l", "/home/u/.mux/session_inboxes/abc-123.jsonl"]],
    not_match = [["wc", "-c", "/home/u/.mux/session_inboxes/abc-123.jsonl"], ["wc", "/home/u/.mux/session_inboxes/abc-123.jsonl"], ["wc", "-l", "/home/u/.mux/session_inboxes/abc-123.jsonl-other"]],
)
`

describe("prepareCodexEnvironment readableFiles (shell reads without asking)", () => {
  let dir: string
  beforeEach(() => { dir = mkdtempSync(join(tmpdir(), "codex-rules-")) })
  afterEach(() => { rmSync(dir, { recursive: true, force: true }) })

  const home = () => join(dir, "session")
  function spec(readableFiles?: CodexEnvironmentSpec["readableFiles"]): CodexEnvironmentSpec {
    return {
      home: home(), workdir: join(dir, "wd"), mcpServers: [], skillsPaths: [],
      credentials: { apiKey: "sk-test", canonicalHome: join(dir, "canonical") }, nativeMemory: false,
      ...(readableFiles ? { readableFiles } : {}),
    }
  }

  test("writes one 0600 rules file named by the caller into <home>/rules, and lists it", async () => {
    const prepared = await prepareCodexEnvironment(spec({ name: "supermux-inbox-abc-123", files: [INBOX_FILE] }))
    const path = join(home(), "rules", "supermux-inbox-abc-123.rules")
    expect(readFileSync(path, "utf8")).toBe(INBOX_RULES)
    expect(statSync(path).mode & 0o777).toBe(0o600)
    expect(statSync(join(home(), "rules")).mode & 0o777).toBe(0o700)
    expect(prepared.files).toEqual([join(home(), "config.toml"), path])
    expect(readdirSync(join(home(), "rules"))).toEqual(["supermux-inbox-abc-123.rules"]) // no temp file left behind
    expect(readFileSync(join(home(), "config.toml"), "utf8")).toContain("memories = false") // config.toml is written as before
  })

  test("without readableFiles no rules folder is made and nothing changes", async () => {
    const prepared = await prepareCodexEnvironment(spec())
    expect(existsSync(join(home(), "rules"))).toBe(false)
    expect(prepared.files).toEqual([join(home(), "config.toml")])
  })

  test("one file per session id: a shared CODEX_HOME keeps every session's rules, and Codex's own default.rules is never touched", async () => {
    mkdirSync(join(home(), "rules"), { recursive: true })
    const mine = 'prefix_rule(pattern = ["npm", "test"], decision = "allow")\n' // what Codex records when the user allows a command
    writeFileSync(join(home(), "rules", "default.rules"), mine)
    await prepareCodexEnvironment(spec({ name: "supermux-inbox-a", files: ["/inbox/a.jsonl"] }))
    await prepareCodexEnvironment(spec({ name: "supermux-inbox-b", files: ["/inbox/b.jsonl"] }))
    expect(readdirSync(join(home(), "rules")).sort()).toEqual(["default.rules", "supermux-inbox-a.rules", "supermux-inbox-b.rules"])
    expect(readFileSync(join(home(), "rules", "default.rules"), "utf8")).toBe(mine)
    expect(readFileSync(join(home(), "rules", "supermux-inbox-a.rules"), "utf8")).toBe(codexReadRules(["/inbox/a.jsonl"]))
    expect(readFileSync(join(home(), "rules", "supermux-inbox-b.rules"), "utf8")).toBe(codexReadRules(["/inbox/b.jsonl"]))
  })

  test("a reused name replaces its file; an empty file list removes it; neither touches the other rules files", async () => {
    await prepareCodexEnvironment(spec({ name: "supermux-inbox-a", files: ["/inbox/a.jsonl"] }))
    await prepareCodexEnvironment(spec({ name: "supermux-inbox-other", files: ["/inbox/o.jsonl"] }))
    await prepareCodexEnvironment(spec({ name: "supermux-inbox-a", files: ["/inbox/a2.jsonl"] }))
    expect(readFileSync(join(home(), "rules", "supermux-inbox-a.rules"), "utf8")).toBe(codexReadRules(["/inbox/a2.jsonl"]))
    const prepared = await prepareCodexEnvironment(spec({ name: "supermux-inbox-a", files: [] }))
    expect(prepared.files).toEqual([join(home(), "config.toml")])
    expect(readdirSync(join(home(), "rules"))).toEqual(["supermux-inbox-other.rules"])
  })

  test("a symlink where the rules file goes is refused, not written through", async () => {
    mkdirSync(join(home(), "rules"), { recursive: true })
    const victim = join(dir, "victim.txt")
    writeFileSync(victim, "keep")
    symlinkSync(victim, join(home(), "rules", "supermux-inbox-a.rules"))
    await expect(prepareCodexEnvironment(spec({ name: "supermux-inbox-a", files: ["/inbox/a.jsonl"] }))).rejects.toThrow(/symlink/)
    expect(readFileSync(victim, "utf8")).toBe("keep")
  })

  test("a bad name or file list is refused with a TypeError before anything is written", async () => {
    const bad: unknown[] = [
      { name: "default", files: [INBOX_FILE] }, { name: "supermux-", files: [INBOX_FILE] }, { name: "supermux-a/b", files: [INBOX_FILE] },
      { name: "supermux-a\\b", files: [INBOX_FILE] }, { name: "other-inbox", files: [INBOX_FILE] }, { name: "supermux-a b", files: [INBOX_FILE] },
      { name: 5, files: [] }, { files: [INBOX_FILE] }, null, "supermux-a", [],
      { name: "supermux-a", files: "/inbox/a.jsonl" }, { name: "supermux-a" }, { name: "supermux-a", files: null },
      ...["relative/a.jsonl", "", "/", "//", "/inbox/", "/inbox//a.jsonl", "/inbox/../a.jsonl", "/inbox/./a.jsonl", 5, null, {}].map(file => ({ name: "supermux-a", files: [INBOX_FILE, file] })),
    ]
    for (const readableFiles of bad) {
      await expect(prepareCodexEnvironment({ ...spec(), readableFiles } as CodexEnvironmentSpec)).rejects.toThrow(/readableFiles/)
      expect(existsSync(home())).toBe(false)
    }
  })

  test("codexReadRules: every file gets its own pair of rules, a repeated file only one", () => {
    const text = codexReadRules(["/a.jsonl", "/b.jsonl", "/a.jsonl"])
    expect(text.match(/^prefix_rule\(/gm)).toHaveLength(4)
    expect(text).toContain('pattern = [["cat", "head", "tail"], "/a.jsonl"]')
    expect(text).toContain('pattern = ["wc", "-l", "/b.jsonl"]')
    expect(codexReadRules([])).toBe("# Generated by supermux. Do not edit by hand.\n")
  })

  // The real CLI decides what the rules mean (and refuses a file that does not parse or whose examples disagree).
  const hasExecpolicy = (() => {
    try { execFileSync("codex", ["execpolicy", "check", "--help"], { stdio: "ignore", timeout: 20_000 }); return true } catch { return false }
  })()
  function check(rules: string, ...command: string[]): { decision?: string } {
    mkdirSync(join(dir, "cli-home"), { recursive: true }) // the CLI warns about a CODEX_HOME that does not exist
    const out = execFileSync("codex", ["execpolicy", "check", "--rules", rules, ...command], { env: { ...process.env, CODEX_HOME: join(dir, "cli-home") }, encoding: "utf8", timeout: 20_000, stdio: ["ignore", "pipe", "ignore"] })
    return JSON.parse(out)
  }
  const decisions = (rules: string, commands: string[][]) => commands.map(command => check(rules, ...command).decision ?? "none")

  test.skipIf(!hasExecpolicy)("codex execpolicy check: the own inbox file is allowed with cat, head, tail and wc -l, nothing else is", async () => {
    await prepareCodexEnvironment(spec({ name: "supermux-inbox-abc-123", files: [INBOX_FILE] }))
    const rules = join(home(), "rules", "supermux-inbox-abc-123.rules")
    const F = INBOX_FILE
    expect(decisions(rules, [["cat", F], ["head", F], ["tail", F], ["wc", "-l", F]])).toEqual(["allow", "allow", "allow", "allow"])
    expect(decisions(rules, [
      ["cat", "/etc/passwd"], ["cat", `${F}-other`], ["cat", "/home/u/.mux/session_inboxes/other.jsonl"], ["cat", "/home/u/.mux/session_inboxes/"],
      ["tail", "-n", "1", F], ["head", "-n", "1", F], ["wc", F], ["wc", "-c", F], ["rm", F], ["sed", "-n", "1p", F], ["cat"], ["tail"],
    ])).toEqual(Array(12).fill("none"))
    // Prefix matching: trailing arguments pass. Accepted, and pinned here so a change in Codex shows up.
    expect(decisions(rules, [["cat", F, "/etc/passwd"], ["wc", "-l", F, "/etc/passwd"]])).toEqual(["allow", "allow"])
  })

  test.skipIf(!hasExecpolicy)("codex execpolicy check: a path with spaces, quotes, a backslash and non-ASCII letters is a valid literal and matches only itself", async () => {
    const odd = '/Users/John "JS" Smith/it\'s\\here/şirket $HOME/a.jsonl'
    await prepareCodexEnvironment(spec({ name: "supermux-inbox-odd", files: [odd, INBOX_FILE] }))
    const rules = join(home(), "rules", "supermux-inbox-odd.rules")
    expect(decisions(rules, [["cat", odd], ["tail", odd], ["wc", "-l", odd], ["cat", INBOX_FILE]])).toEqual(["allow", "allow", "allow", "allow"])
    expect(decisions(rules, [["cat", "/Users/John"], ["cat", `${odd}-other`], ["cat", "/Users/John \"JS\" Smith/it's\\here/şirket $HOME/b.jsonl"]])).toEqual(["none", "none", "none"])
  })
})
