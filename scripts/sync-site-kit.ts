// What's new (#90): bundle the website's real-app kit into the app at a pinned website commit.
//   bun scripts/sync-site-kit.ts <website sha> [--repo ~/projects/supermux-website]
// The kit lives in UstaLabs/supermux-website (app/, the site's own replicas of the app, recorded sessions and the
// feature scenes). The app loads an edition from a data: URL, which can't fetch anything, so the kit is written as
// one self-contained fragment (styles, scripts in load order, Geist inlined) that an edition inlines where it says
// <!--whatsnew-kit-->. KIT_PIN records the website commit and the fragment's sha256; tests/sync-site-kit.test.ts
// fails when the fragment no longer matches it. Bumping the kit = run this with a newer website sha.
import { execFileSync } from "node:child_process"
import { createHash } from "node:crypto"
import { writeFileSync } from "node:fs"
import { homedir } from "node:os"
import { resolve } from "node:path"

export const FRAGMENT_PATH = "apps/ui/src/commonMain/composeResources/files/whatsnew/kit.html"
export const PIN_PATH = "apps/ui/src/commonMain/composeResources/files/whatsnew/KIT_PIN"

const FONTS: Array<[string, string, number]> = [
  ["assets/fonts/geist-400.woff2", "Geist", 400],
  ["assets/fonts/geist-500.woff2", "Geist", 500],
  ["assets/fonts/geist-600.woff2", "Geist", 600],
  ["assets/fonts/geist-mono-400.woff2", "Geist Mono", 400],
]
// one scene per What's new chapter
const SCENES = ["browser", "device", "cards", "offline", "resume", "restart", "settings"]
const STYLES = ["app/app.css", "app/scene-kit.css", ...SCENES.map(n => `app/${n}-scene.css`)]
// load order: the recording before app.js (it reads it as it loads), the runner before its scenes
// the Agents block (auto-resume's waiting Agent row) needs the site's agents and their avatars before app.js
const SCRIPTS = ["app/replay-data.js", "app/agents-data.js", "app/avatar.js", "app/app.js", "app/scene-kit.js", ...SCENES.map(n => `app/${n}-scene.js`)]
export const KIT_FILES = [...FONTS.map(f => f[0]), ...STYLES, ...SCRIPTS]

type Read = (path: string) => Uint8Array

/** The fragment: a header naming the pin, the fonts, the styles, then the scripts, none able to close its own tag. */
export function buildFragment(sha: string, read: Read): string {
  const text = (p: string) => new TextDecoder().decode(read(p))
  const fonts = FONTS.map(([p, family, weight]) =>
    `@font-face{font-family:"${family}";font-weight:${weight};src:url(data:font/woff2;base64,${Buffer.from(read(p)).toString("base64")}) format("woff2")}`).join("\n")
  const styles = STYLES.map(p => `<style>/* ${p} */\n${text(p).replaceAll("</style", "<\\/style")}\n</style>`).join("\n")
  const scripts = SCRIPTS.map(p => `<script>// ${p}\n${text(p).replaceAll("</script", "<\\/script")}\n</script>`).join("\n")
  return `<!-- generated by scripts/sync-site-kit.ts from UstaLabs/supermux-website@${sha}; do not edit, re-run it -->\n` +
    `<style>\n${fonts}\n</style>\n${styles}\n${scripts}\n`
}

if (import.meta.main) {
  const args = process.argv.slice(2)
  const sha = args[0]
  const repoAt = args.indexOf("--repo")
  const repo = repoAt >= 0 ? args[repoAt + 1] : resolve(homedir(), "projects/supermux-website")
  if (!sha) {
    console.error("usage: bun scripts/sync-site-kit.ts <website sha> [--repo <supermux-website checkout>]")
    process.exit(2)
  }
  execFileSync("git", ["-C", repo, "fetch", "-q", "origin"])
  const full = execFileSync("git", ["-C", repo, "rev-parse", `${sha}^{commit}`]).toString().trim()
  const read: Read = p => execFileSync("git", ["-C", repo, "show", `${full}:${p}`], { maxBuffer: 64 << 20 })
  const fragment = buildFragment(full, read)
  const root = resolve(import.meta.dir, "..")
  writeFileSync(resolve(root, FRAGMENT_PATH), fragment)
  const pin = { repo: "UstaLabs/supermux-website", sha: full, sha256: createHash("sha256").update(fragment).digest("hex"), files: KIT_FILES }
  writeFileSync(resolve(root, PIN_PATH), JSON.stringify(pin, null, 2) + "\n")
  console.log(`kit @ ${full.slice(0, 9)}: ${(fragment.length / 1024).toFixed(0)} KiB → ${FRAGMENT_PATH}`)
}
