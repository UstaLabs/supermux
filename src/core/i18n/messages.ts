export type BrokerLang = "en" | "tr"

/** A device's or user's language tag ("tr", "tr-TR", "TR") → a language the broker speaks; anything else is English. */
export function brokerLang(tag?: string | null): BrokerLang {
  if (!tag) return "en"
  const primary = tag.trim().toLowerCase().split(/[-_]/)[0]
  return primary === "tr" ? "tr" : "en"
}

