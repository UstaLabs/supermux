/** Every language's table; English is complete by construction, the rest are checked against it by the test. */
export const MESSAGES: Record<BrokerLang, Record<MessageKey, string>> = { en, tr }

/** [key] in [lang] (English where the language lacks it), with each `{name}` filled from [vars]; unknown ones stay. */
export function t(lang: BrokerLang, key: MessageKey, vars?: Record<string, string | number>): string {
  const text = MESSAGES[lang]?.[key] ?? en[key]
  if (!vars) return text
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole))
}
