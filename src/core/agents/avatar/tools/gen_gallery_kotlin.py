#!/usr/bin/env python3
"""Embed the avatar gallery (../gallery/*.json) into the app: writes AgentAvatarRigExamples.kt.

    python3 src/core/agents/avatar/tools/gen_gallery_kotlin.py
"""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
gallery = os.path.join(here, "../gallery")
order = ["hoot", "miso", "inky", "sprout", "pebble", "boo", "fox", "pip", "ponder", "lev"]
out = os.path.join(here, "../../../../../apps/ui/src/commonMain/kotlin/dev/supermux/ui/session/AgentAvatarRigExamples.kt")
items = []
for key in order:
    f = os.path.join(gallery, key + ".json")
    d = json.load(open(f))
    text = open(f).read().replace("$", "${'$'}")
    items.append(f'    "{d.get("name", key)}" to """{text}""",')
open(out, "w").write("// GENERATED by src/core/agents/avatar/tools/gen_gallery_kotlin.py — the avatar gallery (do not edit).\npackage dev.supermux.ui.session\n\nval AvatarRigExamples: List<Pair<String, String>> = listOf(\n" + "\n".join(items) + "\n)\n")
print("wrote", len(items), "avatars")
